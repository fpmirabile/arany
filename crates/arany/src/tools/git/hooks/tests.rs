use super::super::tests::{environment, fixture, git_program, host_git, scratch};
use super::*;
use std::os::unix::fs::PermissionsExt;

fn detected(temp: &Path, workspace: &Path) -> Option<Hooks> {
    let program = git_program();
    let environment = environment(workspace, &scratch(temp, 800), &temp.join("home"));
    tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap()
        .block_on(detect(&Git::workspace(&program, &environment)))
        .unwrap()
}

fn hook(path: &Path, body: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, format!("#!/bin/sh\n{body}\n")).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
}

#[test]
fn sample_hooks_are_not_active_hooks() {
    let temp = tempfile::tempdir().unwrap();
    let workspace = fixture(temp.path());
    hook(&workspace.join(".git/hooks/pre-commit.sample"), "exit 0");
    assert_eq!(detected(temp.path(), &workspace), None);
    hook(
        &workspace.join(".git/hooks/pre-commit"),
        "# File generated by pre-commit\nexit 0",
    );
    let found = detected(temp.path(), &workspace).unwrap();
    assert_eq!(found.names, ["pre-commit"]);
    assert!(found.pre_commit_framework);
}

#[test]
fn a_hooks_path_hook_or_its_helper_changing_changes_the_digest() {
    let temp = tempfile::tempdir().unwrap();
    let workspace = fixture(temp.path());
    let home = temp.path().join("home");
    hook(
        &workspace.join(".husky/_/pre-commit"),
        ". \"$(dirname \"$0\")/h\"",
    );
    hook(&workspace.join(".husky/_/h"), "exit 0");
    host_git(&workspace, &home, &["config", "core.hooksPath", ".husky/_"]);
    let first = detected(temp.path(), &workspace).unwrap();
    assert_eq!(first.names, ["pre-commit"]);
    assert!(!first.pre_commit_framework);
    assert!(first.directory.ends_with(".husky/_"));
    hook(&workspace.join(".husky/_/h"), "exit 1");
    let edited = detected(temp.path(), &workspace).unwrap();
    assert_ne!(edited.digest, first.digest);
    hook(&workspace.join(".husky/_/commit-msg"), "exit 0");
    assert_eq!(
        detected(temp.path(), &workspace).unwrap().names,
        ["commit-msg", "pre-commit"]
    );
}

fn block_on<T>(future: impl std::future::Future<Output = T>) -> T {
    tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap()
        .block_on(future)
}

fn hooked_runtime(temp: &Path, workspace: &Path) -> crate::tools::ToolRuntime {
    let mut runtime = crate::tools::tests::in_process_runtime(
        workspace,
        serde_json::json!({"workspace_paths":["."],"write":true,"commands":[],"skills":[],"mcp":[]}),
    );
    runtime.config.git = Some(git_program());
    runtime.git_environment = Some(std::sync::Arc::new(environment(
        workspace,
        &scratch(temp, 801),
        &temp.join("home"),
    )));
    runtime
}

fn commit(runtime: &crate::tools::ToolRuntime, path: &str) -> serde_json::Value {
    let intent = runtime
        .intent(
            crate::RunId::new(),
            crate::AgentRunId::new(),
            crate::tools::ToolCall::GitCommit {
                message: "hooked".into(),
                paths: vec![path.into()],
                staged: false,
            },
        )
        .unwrap();
    let observation = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap()
        .block_on(super::super::run(
            runtime,
            intent,
            crate::tools::Cancellation::new(),
        ));
    assert!(observation.valid(), "{observation:?}");
    serde_json::from_str(&observation.output).unwrap()
}

#[test]
fn hooks_run_only_while_accepted_and_unchanged() {
    let temp = tempfile::tempdir().unwrap();
    let workspace = fixture(temp.path());
    let home = temp.path().join("home");
    let marker = temp.path().join("hook-ran");
    hook(
        &workspace.join(".husky/_/pre-commit"),
        &format!("touch {}", marker.display()),
    );
    host_git(&workspace, &home, &["config", "core.hooksPath", ".husky/_"]);
    host_git(&workspace, &home, &["config", "user.name", "Hooked"]);
    host_git(
        &workspace,
        &home,
        &["config", "user.email", "hooked@example.invalid"],
    );
    let accepted = detected(temp.path(), &workspace).unwrap().digest;
    let mut runtime = hooked_runtime(temp.path(), &workspace);

    block_on(runtime.admit_git_hooks(None, true));
    let declined = commit(&runtime, "src/a.txt");
    assert!(declined["commit"].is_string() && declined["hooks_not_run"].is_string());
    assert!(!marker.exists(), "a declined hook ran");

    block_on(runtime.admit_git_hooks(Some(accepted), true));
    assert_eq!(runtime.receipt().git.unwrap().hooks, Some(accepted));
    let ran = commit(&runtime, "src/new.txt");
    assert!(
        ran["commit"].is_string() && ran.get("hooks_not_run").is_none(),
        "{ran}"
    );
    assert!(marker.exists(), "an accepted hook did not run");

    std::fs::remove_file(&marker).unwrap();
    hook(
        &workspace.join(".husky/_/pre-commit"),
        &format!("touch {}; exit 0", marker.display()),
    );
    let edited = commit(&runtime, "src/big.txt");
    assert!(edited["hooks_not_run"].is_string(), "{edited}");
    assert!(!marker.exists(), "an edited hook ran");
}

#[test]
fn without_a_human_hooked_writes_are_offered_only_under_user_allow_rules() {
    let temp = tempfile::tempdir().unwrap();
    let workspace = fixture(temp.path());
    hook(&workspace.join(".git/hooks/pre-commit"), "exit 0");
    let accepted = detected(temp.path(), &workspace).unwrap().digest;
    let mut runtime = hooked_runtime(temp.path(), &workspace);
    let commit = crate::tools::ToolCall::GitCommit {
        message: "m".into(),
        paths: vec![".".into()],
        staged: false,
    };
    let switch = crate::tools::ToolCall::GitSwitch {
        branch: "main".into(),
    };
    let operations = |runtime: &crate::tools::ToolRuntime| {
        let catalog = super::super::catalog(runtime);
        (catalog["operations"].clone(), catalog["writes"].clone())
    };

    block_on(runtime.admit_git_hooks(Some(accepted), true));
    assert!(runtime.allows(&commit) && runtime.allows(&switch));
    assert!(operations(&runtime).1.is_null());

    block_on(runtime.admit_git_hooks(Some(accepted), false));
    assert!(!runtime.allows(&commit) && !runtime.allows(&switch));
    let (listed, contract) = operations(&runtime);
    assert!(
        !listed
            .as_array()
            .unwrap()
            .iter()
            .any(|name| name == "git_commit")
    );
    assert_eq!(contract, super::super::WRITES_LEFT_TO_USER);

    let settings = br#"{"permissions":{"allow":["git_commit"]}}"#;
    runtime.permissions = Some(crate::tools::PermissionSnapshot {
        config: std::sync::Arc::new(
            crate::tools::permissions::PermissionConfig::parse(settings).unwrap(),
        ),
        digest: crate::validate::digest(settings),
    });
    assert!(runtime.allows(&commit) && !runtime.allows(&switch));
    let (listed, contract) = operations(&runtime);
    assert!(
        listed
            .as_array()
            .unwrap()
            .iter()
            .any(|name| name == "git_commit")
    );
    assert!(
        !listed
            .as_array()
            .unwrap()
            .iter()
            .any(|name| name == "git_switch")
    );
    assert_eq!(contract, super::super::WRITES_LEFT_TO_USER);
}

#[test]
fn a_configured_run_honors_only_a_trusted_folders_saved_answer() {
    use crate::tools::WorkspacePermissions;
    crate::test_support::isolate_account_root();
    let temp = tempfile::tempdir().unwrap();
    let workspace = fixture(temp.path());
    let home = temp.path().join("home");
    let marker = temp.path().join("hook-ran");
    hook(
        &workspace.join(".git/hooks/pre-commit"),
        &format!("touch {}", marker.display()),
    );
    host_git(&workspace, &home, &["config", "user.name", "Configured"]);
    host_git(
        &workspace,
        &home,
        &["config", "user.email", "configured@example.invalid"],
    );
    let accepted = detected(temp.path(), &workspace).unwrap().digest;
    let mut runtime = hooked_runtime(temp.path(), &workspace);

    assert_eq!(WorkspacePermissions::saved_git_hooks(&workspace), None);
    block_on(runtime.admit_git_hooks(WorkspacePermissions::saved_git_hooks(&workspace), false));
    let untrusted = commit(&runtime, "src/a.txt");
    assert!(untrusted["hooks_not_run"].is_string(), "{untrusted}");
    assert!(!marker.exists(), "a hook ran without a trust entry");

    let mut trust = WorkspacePermissions::open(&workspace).unwrap();
    trust
        .remember_profiles(true, crate::tools::ApprovalMode::AutoEdits, &[])
        .unwrap();
    trust.remember_hooks_digest(accepted, true).unwrap();
    assert_eq!(
        WorkspacePermissions::saved_git_hooks(&workspace),
        Some(accepted)
    );
    block_on(runtime.admit_git_hooks(WorkspacePermissions::saved_git_hooks(&workspace), false));
    let trusted = commit(&runtime, "src/new.txt");
    assert!(trusted.get("hooks_not_run").is_none(), "{trusted}");
    assert!(marker.exists(), "a saved accepted hook did not run");

    std::fs::remove_file(&marker).unwrap();
    hook(
        &workspace.join(".git/hooks/pre-commit"),
        &format!("touch {}; exit 0", marker.display()),
    );
    block_on(runtime.admit_git_hooks(WorkspacePermissions::saved_git_hooks(&workspace), false));
    assert_eq!(runtime.receipt().git.unwrap().hooks, None);
    let changed = commit(&runtime, "src/big.txt");
    assert!(changed["hooks_not_run"].is_string(), "{changed}");
    assert!(!marker.exists(), "a hook changed after acceptance ran");
}
