use super::super::ToolError;
use super::runner::{Git, Io};
use crate::validate::{digest, hex_digest};
use std::io::Read;
use std::path::{Path, PathBuf};
use std::time::Duration;

const MAX_GIT_HOOK_FILES: usize = 64;
const MAX_GIT_HOOK_BYTES: u64 = 1024 * 1024;
const DETECTION_TIME: Duration = Duration::from_secs(5);
// The hook names Git runs; other files in the directory are helpers they may call.
const HOOK_NAMES: [&str; 28] = [
    "applypatch-msg",
    "pre-applypatch",
    "post-applypatch",
    "pre-commit",
    "pre-merge-commit",
    "prepare-commit-msg",
    "commit-msg",
    "post-commit",
    "pre-rebase",
    "post-checkout",
    "post-merge",
    "pre-push",
    "pre-receive",
    "update",
    "proc-receive",
    "post-receive",
    "post-update",
    "reference-transaction",
    "push-to-checkout",
    "pre-auto-gc",
    "post-rewrite",
    "sendemail-validate",
    "fsmonitor-watchman",
    "p4-changelist",
    "p4-prepare-changelist",
    "p4-post-changelist",
    "p4-pre-submit",
    "post-index-change",
];
// The pre-commit framework writes this line into each hook it installs.
const PRE_COMMIT_MARKER: &[u8] = b"File generated by pre-commit";

// The active hooks directory, the hooks Git would run from it and a digest of every file it holds.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct Hooks {
    pub(crate) directory: PathBuf,
    pub(crate) names: Vec<String>,
    pub(crate) pre_commit_framework: bool,
    pub(crate) digest: [u8; 32],
}

// Finds the hooks the user's configuration activates (`core.hooksPath`, else `.git/hooks`); none is `None`.
pub(crate) async fn detect(git: &Git<'_>) -> Result<Option<Hooks>, ToolError> {
    let deadline = tokio::time::Instant::now() + DETECTION_TIME;
    let configured = git
        .run(
            &["config", "--show-scope", "--get-all", "core.hooksPath"].map(String::from),
            Io::default(),
            deadline,
        )
        .await?;
    // The cage's own `-c core.hooksPath` has command scope; the user's last setting wins over it here.
    let directory = match String::from_utf8_lossy(&configured.stdout)
        .lines()
        .filter_map(|line| line.split_once('\t'))
        .filter(|(scope, _)| *scope != "command")
        .map(|(_, value)| value.to_owned())
        .next_back()
    {
        Some(path) => git.work_tree.join(expand(&path, git)),
        None => {
            let common = git
                .run(
                    &["rev-parse", "--git-common-dir"].map(String::from),
                    Io::default(),
                    deadline,
                )
                .await?;
            if common.status != Some(0) {
                return Ok(None);
            }
            let common = String::from_utf8_lossy(&common.stdout)
                .trim_end()
                .to_owned();
            git.work_tree.join(common).join("hooks")
        }
    };
    tokio::task::spawn_blocking(move || scan(&directory))
        .await
        .map_err(|_| ToolError::Operation)?
}

fn expand(path: &str, git: &Git<'_>) -> PathBuf {
    match path.strip_prefix("~/") {
        Some(rest) => git.environment.home().join(rest),
        None => PathBuf::from(path),
    }
}

fn scan(directory: &Path) -> Result<Option<Hooks>, ToolError> {
    use std::os::unix::fs::PermissionsExt;
    let Ok(entries) = std::fs::read_dir(directory) else {
        return Ok(None);
    };
    let mut files = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|_| ToolError::Operation)?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let metadata = std::fs::metadata(entry.path()).map_err(|_| ToolError::Operation)?;
        if !metadata.is_file() || name.ends_with(".sample") {
            continue;
        }
        if files.len() == MAX_GIT_HOOK_FILES || metadata.len() > MAX_GIT_HOOK_BYTES {
            return Err(ToolError::Limit);
        }
        let mut bytes = Vec::new();
        std::fs::File::open(entry.path())
            .and_then(|file| file.take(MAX_GIT_HOOK_BYTES).read_to_end(&mut bytes))
            .map_err(|_| ToolError::Operation)?;
        let runs =
            HOOK_NAMES.contains(&name.as_str()) && metadata.permissions().mode() & 0o111 != 0;
        files.push((name, bytes, runs));
    }
    if !files.iter().any(|(_, _, runs)| *runs) {
        return Ok(None);
    }
    files.sort();
    let mut pinned = directory.as_os_str().as_encoded_bytes().to_vec();
    for (name, bytes, _) in &files {
        pinned.extend_from_slice(format!("\0{name}\0{}", hex_digest(bytes)).as_bytes());
    }
    Ok(Some(Hooks {
        directory: directory.to_owned(),
        pre_commit_framework: files.iter().any(|(_, bytes, runs)| {
            *runs
                && bytes
                    .windows(PRE_COMMIT_MARKER.len())
                    .any(|window| window == PRE_COMMIT_MARKER)
        }),
        names: files
            .into_iter()
            .filter(|(_, _, runs)| *runs)
            .map(|(name, _, _)| name)
            .collect(),
        digest: digest(&pinned),
    }))
}

