use super::*;

#[test]
fn reset_dates_validate_calendar_offsets_fractions_and_epoch_edges() {
    for (value, expected) in [
        ("1970-01-01T00:00:00Z", 0),
        ("1970-01-01t00:00:00z", 0),
        ("1969-12-31T23:00:00-01:00", 0),
        ("1970-01-01T01:30:00+01:30", 0),
        ("1970-01-01T00:00:00.000000000Z", 0),
        ("1970-01-01T00:00:00.000000001Z", 1),
        ("1970-01-01T00:00:00.9Z", 1),
        ("2000-02-29T00:00:00Z", 951_782_400),
        ("2024-02-29T00:00:00Z", 1_709_164_800),
        ("9999-12-31T23:59:59Z", 253_402_300_799),
    ] {
        assert_eq!(rfc3339_seconds(value), Some(expected), "{value}");
    }
    for value in [
        "",
        "2024-02-30T00:00:00Z",
        "1900-02-29T00:00:00Z",
        "2100-02-29T00:00:00Z",
        "2024-00-01T00:00:00Z",
        "2024-13-01T00:00:00Z",
        "2024-01-00T00:00:00Z",
        "2024-04-31T00:00:00Z",
        "2024-01-01T24:00:00Z",
        "2024-01-01T00:60:00Z",
        "2024-01-01T00:00:60Z",
        "2024-01-01T00:00:00",
        "2024-01-01T00:00:00.Z",
        "2024-01-01T00:00:00.1234567890Z",
        "2024-01-01T00:00:00+24:00",
        "2024-01-01T00:00:00+00:60",
        "2024-01-01T00:00:00Z ",
        "2024-01-01 00:00:00Z",
        "２０２４-01-01T00:00:00Z",
    ] {
        assert_eq!(rfc3339_seconds(value), None, "{value}");
    }
    for year in [1970, 1900, 2000, 2024, 2100, 9999] {
        for month in 1..=12 {
            let value = format!("{year:04}-{month:02}-01T00:00:00Z");
            if let Ok(seconds) = u64::try_from(rfc3339_seconds(&value).unwrap()) {
                assert_eq!(
                    utc_date(seconds),
                    (
                        u64::try_from(year).unwrap(),
                        u64::try_from(month).unwrap(),
                        1
                    )
                );
            }
        }
    }
}
